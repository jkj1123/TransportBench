"""
L_D_HyperDeepONet: Low-Rank HyperDeepONet (model_L_hyperdeeponet.py) with a
directly-learned, SHARED full-rank backbone added to each middle trunk
layer's condition-dependent low-rank weight:

    W_l(b) = W_{0,l} + a * U_l(b) V_l(b)^T

where `a` is a FIXED (non-learnable) scalar, default 1.0. Set a<1 (e.g.
0.01) to force the shared backbone W0 to carry relatively more of the
effective weight -- motivated by finding that with a=1.0, the trained
model's ||U(b)V(b)^T|| naturally dominates ||W0|| by ~30-100x (the
optimizer largely ignores W0), which made this ablation behave almost
identically to the original Low-Rank HyperDeepONet.

W_{0,l} is an ordinary nn.Parameter (full shape [d_out, d_in], NOT low-rank,
NOT generated by the branch/hypernetwork -- independent of the branch input
b). U_l(b), V_l(b)^T are still generated by the branch net exactly as in
the original Low-Rank HyperDeepONet (same rank r, same param count from
branch, same bias treatment).

Implementation note on how W_l(b) is applied: the original code never
materializes the full [d_out, d_in] low-rank product U V^T -- it applies it
to the trunk activation y in two cheaper steps (z = V^T @ y, then U @ z),
which is mathematically identical to (U V^T) @ y but avoids ever forming
the full matrix. Adding W0 preserves this: since matrix multiplication
distributes over addition,

    W_l(b) @ y = (W_{0,l} + U_l(b) V_l(b)^T) @ y
               = W_{0,l} @ y  +  U_l(b) (V_l(b)^T @ y)

so we just add one more einsum term (W_{0,l} @ y, batched only over the
input y since W_{0,l} itself is shared/not batched) alongside the existing
two-step low-rank term, and add both into the same bias/activation. No
explicit [B, d_out, d_in] tensor is ever constructed, exactly as before.

Everything else (trunk_dims, rank r, first/last full-rank generated
layers, bias treatment, activation, branch net architecture, t_para /
branch output width, and the fact that the branch's effect enters ONLY
through the generated weights -- no separate branch-trunk dot product) is
unchanged from model_L_hyperdeeponet.py.
"""

import math
import torch
import torch.nn as nn


class HyperDeepONet(nn.Module):
    def __init__(self, branch_dim=674, trunk_dim=2, hidden_dim=46,
                 num_outputs=4, trunk_depth=3, branch_depth=3,
                 activation='GELU', a=1.0):
        """
        a: FIXED (non-learnable) scalar multiplier on the conditional
        low-rank term, applied as W_l(b) = W0_l + a * U_l(b) V_l(b)^T.
        Analysis of the unconstrained (a=1.0) version showed the low-rank
        term's norm naturally dominates W0's by ~30-100x; a<1 forces the
        shared backbone W0 to carry relatively more of the effective
        weight. Just a plain float, not an nn.Parameter -- not learned.
        """
        super().__init__()
        self.a = a

        if activation == 'Tanh':
            act = nn.Tanh
            self._trunk_act = torch.tanh
        elif activation == 'GELU':
            act = nn.GELU
            self._trunk_act = nn.functional.gelu
        else:
            raise ValueError(f"Unsupported activation: {activation}")

        # Trunk architecture: [trunk_dim, hidden, ..., hidden, num_outputs]
        self.trunk_dims = [trunk_dim] + [hidden_dim] * trunk_depth + [num_outputs]

        # Total parameters needed from the branch (hypernetwork) -- UNCHANGED
        # from model_L_hyperdeeponet.py. W0 is NOT part of this -- it is a
        # directly-learned model parameter, not generated by the branch.
        t_para = 0
        r = 8  # same rank as the existing Low-Rank HyperDeepONet

        for i in range(1):
            t_para += self.trunk_dims[i] * self.trunk_dims[i + 1] + self.trunk_dims[i + 1]

        for i in range(1, len(self.trunk_dims) - 2):
            d_in = self.trunk_dims[i]
            d_out = self.trunk_dims[i + 1]

            t_para += d_out * r
            t_para += r * d_in
            t_para += d_out

        for i in range(len(self.trunk_dims) - 2, len(self.trunk_dims) - 1):
            t_para += self.trunk_dims[i] * self.trunk_dims[i + 1] + self.trunk_dims[i + 1]

        # Branch: single network -> t_para (trunk weights/biases), same as before
        branch_dims = [branch_dim] + [hidden_dim] * branch_depth + [t_para]
        self.branch_net = _MLP(branch_dims, act)

        # --- NEW: shared, directly-learned, full-rank W_{0,l} for each
        # middle (low-rank) trunk layer. One nn.Parameter per middle layer,
        # shape [d_out, d_in] (matches nn.Linear's weight orientation),
        # initialized with the same scheme PyTorch's nn.Linear uses by
        # default (kaiming_uniform_ with a=sqrt(5)).
        self.W0_list = nn.ParameterList()
        for i in range(1, len(self.trunk_dims) - 2):
            d_in = self.trunk_dims[i]
            d_out = self.trunk_dims[i + 1]
            w0 = nn.Parameter(torch.empty(d_out, d_in))
            nn.init.kaiming_uniform_(w0, a=math.sqrt(5))
            self.W0_list.append(w0)

        self.num_outputs = num_outputs

    def _branch_forward(self, x):
        """Run branch net on x -> trunk parameters."""
        return self.branch_net(x)  # [B, t_para]

    def _trunk_forward(self, params, x_trunk):
        """Hypernetwork trunk: params -> weights/biases -> forward pass."""
        B = params.shape[0]  # use branch batch size (handles shared trunk)
        # Normalize to 3D: [B, N, trunk_dim]
        if x_trunk.dim() == 2:
            x_trunk = x_trunk.unsqueeze(0).expand(B, -1, -1)

        _, N, _ = x_trunk.shape
        y = x_trunk  # [B, N, trunk_dim]
        start = 0
        r = 8

        # First layer: full-rank, branch-generated (unchanged)
        for i in range(1):
            d_in, d_out = self.trunk_dims[i], self.trunk_dims[i + 1]

            w_sz = d_in * d_out
            weight = params[:, start:start + w_sz].reshape(B, d_out, d_in)
            start += w_sz
            bias = params[:, start:start + d_out].reshape(B, 1, d_out)
            start += d_out

            y = torch.einsum("bij,bgj->bgi", weight, y) + bias  # [B, N, d_out]
            y = self._trunk_act(y)

        # Middle layers: W_l(b) = W_{0,l} + U_l(b) V_l(b)^T, applied as
        # W0 @ y  +  U @ (V^T @ y)  (never materializing the full matrix).
        w0_idx = 0
        for i in range(1, len(self.trunk_dims) - 2):
            d_in, d_out = self.trunk_dims[i], self.trunk_dims[i + 1]

            weight1 = params[:, start:start + d_out * r].reshape(B, d_out, r)  # U(b)
            start += d_out * r

            weight2 = params[:, start:start + r * d_in].reshape(B, r, d_in)    # V(b)^T
            start += r * d_in

            bias = params[:, start:start + d_out].reshape(B, 1, d_out)
            start += d_out

            W0 = self.W0_list[w0_idx]  # [d_out, d_in], shared (no batch dim)
            w0_idx += 1

            y_shared = torch.einsum("ij,bgj->bgi", W0, y)          # W0 @ y,      [B, N, d_out]
            z = torch.einsum("brj,bgj->bgr", weight2, y)            # V(b)^T @ y,  [B, N, r]
            y_lowrank = torch.einsum("bir,bgr->bgi", weight1, z)    # U(b) @ z,    [B, N, d_out]

            y = y_shared + self.a * y_lowrank + bias
            y = self._trunk_act(y)

        # Last layer: full-rank, branch-generated, no activation (unchanged)
        d_in, d_out = self.trunk_dims[-2], self.trunk_dims[-1]
        w_sz = d_in * d_out
        weight = params[:, start:start + w_sz].reshape(B, d_out, d_in)
        start += w_sz
        bias = params[:, start:start + d_out].reshape(B, 1, d_out)
        start += d_out

        y = torch.einsum("bij,bgj->bgi", weight, y) + bias  # [B, N, num_outputs]
        return y

    def forward(self, x_branch, x_trunk):
        """
        Args:
            x_branch: [B, branch_dim]  sensor values
            x_trunk:  [N, trunk_dim] or [B, N, trunk_dim]  query coordinates

        Returns:
            [B, N, num_outputs]
        """
        params = self._branch_forward(x_branch)  # [B, t_para]
        return self._trunk_forward(params, x_trunk)


class _MLP(nn.Module):
    """Simple fully-connected stack: Linear -> Act -> ... -> Linear."""
    def __init__(self, dims, act):
        super().__init__()
        layers = []
        for i in range(len(dims) - 2):
            layers.append(nn.Linear(dims[i], dims[i + 1]))
            layers.append(act())
        layers.append(nn.Linear(dims[-2], dims[-1]))
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x)
