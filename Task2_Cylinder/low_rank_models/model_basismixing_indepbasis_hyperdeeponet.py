"""
Ablation of model_basismixing_hyperdeeponet.py (not modified by this file):
removes Branch 1 (the shared MLP that generated the K=num_basis weight/bias
bases from a scalar mode index) and replaces it with K independent
nn.Parameter tensors per trunk layer, learned directly (not generated by any
network). Branch 2 (the per-sample mixing-coefficient MLP, and the
coeff_offset=0.1 fix applied in exactly the same place/way -- added to
Branch 2's raw output before mixing) is unchanged.

    original: B_{l,k} = f_theta(l, k)                      (Branch 1 MLP)
    this file: B_{l,k} = independent nn.Parameter, per layer l, per mode k

    W_l(c) = (1/sqrt(K)) * sum_k s_{l,k}(c) * W_{l,k}        (unchanged)
    b_l(c) = (1/sqrt(K)) * sum_k s_{l,k}(c) * b_{l,k}        (unchanged)

Everything else -- trunk architecture/activation (GELU/Tanh), the batched
trunk forward pass (model_hyperdeeponet-style weight/bias application,
last layer unactivated), 2D/3D x_trunk handling, [B, N, num_outputs]
output, and the mixing formula itself (same layer-shared mixing
coefficient for weight and bias, basis mixing also applied to the final
output layer, no W_0/residual path) -- is identical in spirit to
model_basismixing_hyperdeeponet.py. This is a single, isolated ablation
(swap Branch 1's MLP for free parameters); no other architectural change is
introduced.

Initialization: each layer's weight-basis tensor [K, d_out, d_in] is
Kaiming-uniform initialized per the standard nn.Linear scheme (fan_in=d_in),
then rescaled so that the EFFECTIVE mixed weight W_l(c) -- accounting for
Branch 2's actual output scale at init AND the coeff_offset=0.1 -- lands
at that same standard per-entry variance (1/(3*d_in), matching PyTorch's
own nn.Linear default), instead of the raw basis entries themselves having
that variance (which would make the K-term mixed sum's variance far too
small, given Branch 2's typically small, offset-dominated coefficients).
See `_calibrate_basis_scale()`.
"""

import math
import torch
import torch.nn as nn


class BasisMixingIndepBasisHyperDeepONet(nn.Module):
    def __init__(self, branch_dim=674, trunk_dim=2, hidden_dim=46,
                 num_outputs=4, trunk_depth=3,
                 num_basis=20,
                 branch2_hidden_dim=48, branch2_depth=2,
                 activation='GELU', coeff_offset=0.1):
        super().__init__()

        if activation == 'Tanh':
            act = nn.Tanh
            self._trunk_act = torch.tanh
        elif activation == 'GELU':
            act = nn.GELU
            self._trunk_act = nn.functional.gelu
        else:
            raise ValueError(f"Unsupported activation: {activation}")

        self.trunk_dims = [trunk_dim] + [hidden_dim] * trunk_depth + [num_outputs]
        self.num_basis = num_basis
        self.coeff_offset = coeff_offset

        self.block_sizes = [self.trunk_dims[i] * self.trunk_dims[i + 1] + self.trunk_dims[i + 1]
                             for i in range(len(self.trunk_dims) - 1)]
        self.L = len(self.block_sizes)
        self.layer_dims = [(self.trunk_dims[i], self.trunk_dims[i + 1]) for i in range(self.L)]
        t_para = sum(self.block_sizes)
        self.t_para = t_para

        # --- Independent weight/bias basis parameters (this ablation's only
        # structural change: no Branch 1 MLP -- K bases per layer, learned
        # directly). Standard Kaiming-uniform init per layer (fan_in=d_in),
        # calibrated below to compensate for the K-term mixing + offset.
        self.weight_basis = nn.ParameterList()
        self.bias_basis = nn.ParameterList()
        for (d_in, d_out) in self.layer_dims:
            w = torch.empty(num_basis, d_out, d_in)
            nn.init.kaiming_uniform_(w.view(num_basis * d_out, d_in), a=math.sqrt(5))
            self.weight_basis.append(nn.Parameter(w))
            bound = 1.0 / math.sqrt(d_in) if d_in > 0 else 0.0
            b = torch.empty(num_basis, d_out).uniform_(-bound, bound)
            self.bias_basis.append(nn.Parameter(b))

        # --- Branch 2: per-sample mixing-coefficient generator (unchanged). ---
        branch2_dims = [branch_dim] + [branch2_hidden_dim] * branch2_depth + [self.L * num_basis]
        self.branch2_net = _MLP(branch2_dims, act)

        self.num_outputs = num_outputs

        self._calibrate_basis_scale(branch_dim)

    @torch.no_grad()
    def _calibrate_basis_scale(self, branch_dim, n_probe=256):
        """Rescale each layer's weight/bias basis so the EFFECTIVE mixed
        weight/bias at init has the standard nn.Linear per-entry variance
        (1/(3*d_in)), given Branch 2's actual output scale (measured with a
        probe batch) and the fixed coeff_offset. See module docstring."""
        probe = torch.randn(n_probe, branch_dim)
        raw = self.branch2_net(probe).view(n_probe, self.L, self.num_basis)
        s = raw + self.coeff_offset
        # E[s_{l,k}^2], averaged over the probe batch and over k (modes are
        # structurally interchangeable, so one scale per layer is enough).
        mean_sq = s.pow(2).mean(dim=(0, 2))  # [L]

        for l, (d_in, d_out) in enumerate(self.layer_dims):
            # weight_basis[l]/bias_basis[l] were already Kaiming-initialized
            # to the standard per-entry variance target_var = 1/(3*d_in)
            # (PyTorch's own nn.Linear default). Var(W_l) ~= E[s_k^2] *
            # Var(basis_entry) (derivation in the module docstring), so to
            # land the MIXED weight back at that same target_var we must
            # rescale the basis entries by 1/sqrt(E[s_k^2]) -- NOT by
            # sqrt(target_var)/sqrt(E[s_k^2]) (that extra sqrt(target_var)
            # factor was a bug: it double-counted target_var, since the
            # basis already started at std=sqrt(target_var)).
            current_scale = mean_sq[l].clamp(min=1e-12).sqrt().item()
            factor = 1.0 / current_scale
            self.weight_basis[l].data.mul_(factor)
            self.bias_basis[l].data.mul_(factor)

    def _mixing_forward(self, x_branch):
        """Branch 2 (unchanged): per-sample, per-layer mixing coefficients,
        with coeff_offset applied in the same place as the original.
        Returns: [B, L, num_basis]."""
        B = x_branch.shape[0]
        return self.branch2_net(x_branch).view(B, self.L, self.num_basis) + self.coeff_offset

    def _mixed_layer_params(self, coeffs):
        """Mix each layer's independent basis parameters with Branch 2's
        per-sample coefficients.

        Args:
            coeffs: [B, L, num_basis]

        Returns:
            list of (weight, bias) per layer, weight: [B, d_out, d_in], bias: [B, d_out].
        """
        scale = 1.0 / math.sqrt(self.num_basis)
        out = []
        for l in range(self.L):
            coeffs_l = coeffs[:, l, :]                                    # [B, K]
            W = scale * torch.einsum('bk,koi->boi', coeffs_l, self.weight_basis[l])  # [B, d_out, d_in]
            b = scale * torch.einsum('bk,ko->bo', coeffs_l, self.bias_basis[l])       # [B, d_out]
            out.append((W, b))
        return out

    def _trunk_forward(self, layer_params, x_trunk):
        """Batched trunk forward pass -- same computation as
        model_hyperdeeponet.HyperDeepONet._trunk_forward (same per-layer
        activation, last layer unactivated), just consuming a list of
        per-layer (weight, bias) tensors directly instead of a flattened
        `params` vector."""
        B = layer_params[0][0].shape[0]
        if x_trunk.dim() == 2:
            x_trunk = x_trunk.unsqueeze(0).expand(B, -1, -1)

        y = x_trunk  # [B, N, trunk_dim]

        for i in range(self.L - 1):
            weight, bias = layer_params[i]
            y = torch.einsum("bij,bgj->bgi", weight, y) + bias.unsqueeze(1)  # [B, N, d_out]
            y = self._trunk_act(y)

        # Last layer: no activation
        weight, bias = layer_params[-1]
        y = torch.einsum("bij,bgj->bgi", weight, y) + bias.unsqueeze(1)
        return y

    def forward(self, x_branch, x_trunk):
        """
        Args:
            x_branch: [B, branch_dim]  sensor values (Ma, Kn)
            x_trunk:  [N, trunk_dim] or [B, N, trunk_dim]  query coordinates

        Returns:
            [B, N, num_outputs]
        """
        coeffs = self._mixing_forward(x_branch)            # [B, L, num_basis]
        layer_params = self._mixed_layer_params(coeffs)     # per-layer (weight, bias)
        return self._trunk_forward(layer_params, x_trunk)

    # ---- diagnostics ----

    def diagnose(self, x_branch, x_trunk, verbose=True):
        """Per-layer effective-weight scale, mixing-coefficient RMS,
        dead-layer warning, output-sensitivity-to-coordinates check, and
        NaN/Inf flags."""
        with torch.no_grad():
            coeffs = self._mixing_forward(x_branch)
            layer_params = self._mixed_layer_params(coeffs)

            per_layer_rms = coeffs.pow(2).mean(dim=(0, 2)).sqrt()  # [L]
            stats = {
                'coeffs_std': coeffs.std().item(),
                'per_layer_coeff_rms': per_layer_rms.tolist(),
                'dead_layer_warning': [l for l, v in enumerate(per_layer_rms.tolist()) if v < 1e-3],
            }
            for l, (W, b) in enumerate(layer_params):
                stats[f'layer{l}_weight_mean'] = W.mean().item()
                stats[f'layer{l}_weight_std'] = W.std().item()
                stats[f'layer{l}_weight_norm_per_sample'] = W.flatten(1).norm(dim=1).mean().item()
                stats[f'layer{l}_bias_std'] = b.std().item()
                stats['has_nan' if l == 0 else f'_has_nan_{l}'] = bool(torch.isnan(W).any() or torch.isnan(b).any())
                stats['has_inf' if l == 0 else f'_has_inf_{l}'] = bool(torch.isinf(W).any() or torch.isinf(b).any())

            y = self._trunk_forward(layer_params, x_trunk)
            stats['output_std'] = y.std().item()
            stats['output_has_nan'] = bool(torch.isnan(y).any())
            stats['output_has_inf'] = bool(torch.isinf(y).any())

            # First-layer coordinate sensitivity: perturb x_trunk and see
            # whether the output actually changes (catches the exact
            # collapse seen before: layer-0 mixing -> 0 makes the trunk
            # blind to x_trunk entirely).
            if x_trunk.dim() == 2:
                xt_batched = x_trunk.unsqueeze(0).expand(x_branch.shape[0], -1, -1)
            else:
                xt_batched = x_trunk
            y0 = self._trunk_forward(layer_params, xt_batched)
            y1 = self._trunk_forward(layer_params, xt_batched + 0.1)
            stats['coord_sensitivity_maxdiff'] = (y1 - y0).abs().max().item()

        if verbose:
            print("=== BasisMixingIndepBasisHyperDeepONet diagnostics ===")
            for k, v in stats.items():
                print(f"  {k}: {v}")
        return stats


class _MLP(nn.Module):
    """Simple fully-connected stack: Linear -> Act -> ... -> Linear."""
    def __init__(self, dims, act):
        super().__init__()
        layers = []
        for i in range(len(dims) - 2):
            layers.append(nn.Linear(dims[i], dims[i + 1]))
            layers.append(act())
        layers.append(nn.Linear(dims[-2], dims[-1]))
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x)


def count_params(branch_dim=2, trunk_dim=2, hidden_dim=46, num_outputs=4, trunk_depth=3,
                  num_basis=20, branch2_hidden_dim=48, branch2_depth=2,
                  activation='GELU', coeff_offset=0.1):
    """Instantiate a BasisMixingIndepBasisHyperDeepONet with the given
    config and return (total_params, breakdown_dict), for the ~200K
    parameter-budget search."""
    m = BasisMixingIndepBasisHyperDeepONet(branch_dim=branch_dim, trunk_dim=trunk_dim, hidden_dim=hidden_dim,
                                           num_outputs=num_outputs, trunk_depth=trunk_depth, num_basis=num_basis,
                                           branch2_hidden_dim=branch2_hidden_dim, branch2_depth=branch2_depth,
                                           activation=activation, coeff_offset=coeff_offset)
    basis_params = sum(p.numel() for p in m.weight_basis) + sum(p.numel() for p in m.bias_basis)
    branch2_params = sum(p.numel() for p in m.branch2_net.parameters())
    total = basis_params + branch2_params
    return total, {'basis_params': basis_params, 'branch2_params': branch2_params, 't_para': m.t_para, 'L': m.L}
