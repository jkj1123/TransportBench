"""
W-DeepONet: standard DeepONet (Lu et al.) with the trunk net replaced by a
genuine Wavelet Neural Network (WNN) layer, instead of an MLP.

Branch net: unchanged from BoltzmannDeepONet (model_deeponet.py) -- plain MLP,
outputs num_basis * num_outputs branch coefficients.

Trunk net: a single WaveletTrunk layer. Each of `num_basis` units directly
computes an axis-aligned ANISOTROPIC Mexican-hat wavelet of the input
coordinate -- a separate dilation per input dimension, so each basis
function's footprint is an axis-aligned ellipse (not a circle):

    psi_i(x) = (1 - r_i^2) * exp(-r_i^2 / 2),
    r_i^2 = sum_d ((x_d - b_{i,d}) / a_{i,d})^2

with per-basis learnable translation b_i (in R^trunk_dim) and PER-DIMENSION
dilation a_i (in R^trunk_dim, kept positive via exp of a log-parameter).
This generalizes the classic (isotropic) WNN construction (Zhang &
Benveniste, 1992) to let each basis stretch independently along x/y --
useful when the underlying field has direction-dependent structure (e.g. a
wake elongated downstream), which a single isotropic radius cannot capture
efficiently.

The branch/trunk outputs are combined exactly as in the original DeepONet
(dot product over the shared basis dimension), so this is a drop-in
trunk-only ablation of BoltzmannDeepONet.
"""

import torch
import torch.nn as nn


class WaveletTrunk(nn.Module):
    """Anisotropic (axis-aligned) Mexican-hat wavelet basis layer:
    R^trunk_dim -> R^num_basis. Each basis has its own per-dimension
    dilation, so its footprint is an axis-aligned ellipse, not a circle."""

    def __init__(self, trunk_dim, num_basis, coord_range=None):
        super().__init__()
        self.trunk_dim = trunk_dim
        self.num_basis = num_basis

        if coord_range is None:
            # Fallback: assume roughly unit-scale coordinates.
            lo = torch.full((trunk_dim,), -1.0)
            hi = torch.full((trunk_dim,), 1.0)
        else:
            lo = torch.tensor([c[0] for c in coord_range], dtype=torch.float32)
            hi = torch.tensor([c[1] for c in coord_range], dtype=torch.float32)

        # Translations: spread uniformly at random over the actual coordinate
        # domain, so the basis functions cover the physical grid from init.
        b_init = lo + torch.rand(num_basis, trunk_dim) * (hi - lo)
        self.b = nn.Parameter(b_init)

        # Dilation: PER-DIMENSION now (anisotropic). Init each dimension's
        # scale from that dimension's own extent (not the isotropic domain
        # area), so e.g. the wider x-range starts with a proportionally
        # wider initial footprint than the narrower y-range.
        avg_spacing_per_dim = (domain_extent := (hi - lo)) / (num_basis ** (1.0 / trunk_dim))
        avg_spacing_per_dim = avg_spacing_per_dim.clamp(min=1e-3)
        log_a0 = torch.log(avg_spacing_per_dim)  # [D]
        self.log_a = nn.Parameter(log_a0.unsqueeze(0).repeat(num_basis, 1))  # [P, D]

    def forward(self, x_trunk):
        """
        Args:
            x_trunk: [N, trunk_dim] or [B, N, trunk_dim]
        Returns:
            [N, num_basis] or [B, N, num_basis]
        """
        a = torch.exp(self.log_a)  # [P, D], kept positive, per-dimension
        diff = x_trunk.unsqueeze(-2) - self.b  # [..., N, P, D]
        r2 = ((diff / a) ** 2).sum(dim=-1)  # [..., N, P] -- anisotropic radius^2
        psi = (1.0 - r2) * torch.exp(-0.5 * r2)  # Mexican-hat wavelet
        return psi


class W_DeepONet(nn.Module):
    def __init__(self, branch_dim, trunk_dim, hidden_dim=256, num_basis=124,
                 num_outputs=4, depth=5, activation='GELU', coord_range=None):
        """
        DeepONet with a Wavelet Neural Network trunk (see module docstring).

        `hidden_dim` controls only the branch net's internal MLP width;
        `num_basis` is the shared branch/trunk basis size (p in the DeepONet
        dot-product), generated by the WaveletTrunk instead of an MLP.
        """
        super().__init__()

        if activation == 'GELU':
            self.act = nn.GELU()
        elif activation == 'Tanh':
            self.act = nn.Tanh()
        else:
            raise ValueError(f"Unsupported activation: {activation}")

        # Branch Net (identical pattern to BoltzmannDeepONet, output width
        # is num_basis * num_outputs instead of hidden_dim * num_outputs).
        branch_layers = []
        branch_layers.extend([nn.Linear(branch_dim, hidden_dim), self.act])
        for _ in range(depth - 1):
            branch_layers.extend([nn.Linear(hidden_dim, hidden_dim), self.act])
        branch_layers.append(nn.Linear(hidden_dim, num_basis * num_outputs))
        self.branch_net = nn.Sequential(*branch_layers)

        # Trunk Net: Wavelet Neural Network layer (no MLP, no activation
        # stack -- the wavelet itself is the nonlinearity).
        self.trunk_net = WaveletTrunk(trunk_dim, num_basis, coord_range=coord_range)

        self.num_outputs = num_outputs
        self.num_basis = num_basis

    def forward(self, x_branch, x_trunk):
        # B_out: [Batch, num_basis * num_outputs]
        B_out = self.branch_net(x_branch)
        # T_out: [N_points, num_basis]
        T_out = self.trunk_net(x_trunk)

        B_out_reshaped = B_out.view(-1, self.num_outputs, self.num_basis)

        # Dot Product: "bkh, nh -> bkn"
        prediction = torch.einsum("bkh, nh -> bkn", B_out_reshaped, T_out)
        prediction = prediction.permute(0, 2, 1)

        return prediction
